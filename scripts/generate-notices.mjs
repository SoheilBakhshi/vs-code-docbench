// Regenerates THIRD-PARTY-NOTICES.md from node_modules: the packages bundled into the webviews plus
// their runtime dependencies, with each package's own licence text. Run: node scripts/generate-notices.mjs
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

// Packages with data files copied verbatim into media/ (see esbuild.mjs copyStatic); the rest is derived below.
const ROOTS = ['xlsx', 'x-data-spreadsheet', 'docx-preview', 'pdfjs-dist', 'vditor', 'chart.js', 'jszip'];
const NODE_MODULES = 'node_modules';

const read = (p) => JSON.parse(readFileSync(p, 'utf8'));
const pkgDir = (name) => join(NODE_MODULES, name);

function licenseText(dir) {
  const file = readdirSync(dir).find((f) => /^(licen[sc]e|copying)(\.(md|txt))?$/i.test(f));
  return file ? readFileSync(join(dir, file), 'utf8').trim() : undefined;
}

// Which packages really end up in the shipped bundles: ask esbuild (metafile), not the dependency tree
// (packages such as vditor list build-time tools as dependencies that are never bundled).
import * as esbuild from 'esbuild';
const entries = [
  'src/extension.ts',
  'src/extension-web.ts',
  ...readdirSync('src/webview', { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join('src/webview', d.name, 'index.ts')))
    .map((d) => join('src/webview', d.name, 'index.ts')),
];
const used = new Set(ROOTS.filter((r) => r === 'vditor' || r === 'pdfjs-dist')); // data files are copied as well
for (const entry of entries) {
  const node = entry.includes('extension');
  const result = await esbuild.build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    metafile: true,
    logLevel: 'silent',
    platform: node ? 'node' : 'browser',
    external: ['vscode'],
    loader: { '.svg': 'dataurl', '.png': 'dataurl', '.woff': 'dataurl', '.woff2': 'dataurl', '.ttf': 'dataurl' },
    outdir: 'out-notices-tmp',
  });
  for (const input of Object.keys(result.metafile.inputs)) {
    const m = /node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(input.split('\\').join('/'));
    if (m) used.add(m[1]);
  }
}
const seen = new Map();
for (const name of used) {
  if (existsSync(join(pkgDir(name), 'package.json'))) seen.set(name, read(join(pkgDir(name), 'package.json')));
}

const repoUrl = (p) => {
  const r = typeof p.repository === 'string' ? p.repository : p.repository?.url;
  return (r ?? p.homepage ?? '').replace(/^git\+/, '').replace(/\.git$/, '').replace(/^git:\/\//, 'https://');
};

// Data files that are copied verbatim from pdfjs-dist (see esbuild.mjs copyStatic).
const pdfjs = pkgDir('pdfjs-dist');
const extra = [
  ['Lute Markdown engine (shipped via Vditor, Mulan PSL v2)', join('scripts', 'licenses', 'lute-LICENSE.txt')],
  ['highlight.js (shipped via Vditor)', join(pkgDir('vditor'), 'dist', 'js', 'highlight.js', 'LICENSE')],
  ['pdf.js character maps (cmaps)', join(pdfjs, 'cmaps', 'LICENSE')],
  ['pdf.js standard fonts: Foxit', join(pdfjs, 'standard_fonts', 'LICENSE_FOXIT')],
  ['pdf.js standard fonts: Liberation', join(pdfjs, 'standard_fonts', 'LICENSE_LIBERATION')],
].filter(([, f]) => existsSync(f));

const names = [...seen.keys()].sort();
let out = `# Third-party notices

Docbench itself is MIT licensed (see [LICENSE](LICENSE)). It bundles the open-source software below.
This file is generated by \`scripts/generate-notices.mjs\`; each package's own licence text follows.

JSZip is available under "MIT OR GPL-3.0-or-later"; Docbench uses it under the **MIT** licence.

## Notes on bundled data

- **Vditor** (MIT): only its content themes, emoji images, the Ant Design based icon set
  (\`js/icons/ant.js\`, MIT), the English UI strings and the **Lute** Markdown engine
  (\`js/lute/lute.min.js\`, https://github.com/88250/lute, Mulan PSL v2, unmodified; its licence is reproduced at the end of this file) are shipped.
  Vditor's own script is bundled with one change: addresses of outside services (its default CDN, remote PlantUML rendering,
  video embeds and help links) are replaced at build time, see \`esbuild.mjs\`.
- **Mermaid** (MIT, https://github.com/mermaid-js/mermaid), **KaTeX** (MIT, https://github.com/KaTeX/KaTeX, with its fonts and the mhchem extension)
  and **highlight.js** (BSD-3-Clause, https://github.com/highlightjs/highlight.js) are shipped as the prebuilt files in Vditor's \`dist/js\`
  folder, for diagrams, maths and code highlighting in the Markdown editor. Mermaid's bundle embeds its own dependencies
  (d3, dagre, DOMPurify, Cytoscape, ...); their licences are in the Mermaid repository. The highlight.js licence is reproduced at the end of this file.
- **pdf.js** data files are shipped with their licences reproduced at the end of this file.
- **pdf.js WebAssembly decoders** (JBIG2, OpenJPEG, QCMS) are shipped in media/pdf/wasm/ together with their own LICENSE_* files.
  pdf.js's QuickJS scripting sandbox is not shipped.
- **JSZip**'s and **SheetJS**'s distributed bundles embed small sub-libraries: pako (MIT AND Zlib), lie,
  readable-stream and setimmediate (MIT) inside JSZip; cfb, ssf, codepage, crc-32, adler-32, frac, word and
  wmf (Apache-2.0, all by SheetJS) inside SheetJS. They are covered by the notices of the package that carries them.

## Packages

| Package | Version | Licence | Source |
|---|---|---|---|
`;
for (const n of names) {
  const p = seen.get(n);
  out += `| ${n} | ${p.version} | ${typeof p.license === 'string' ? p.license : JSON.stringify(p.license ?? p.licenses)} | ${repoUrl(p)} |\n`;
}
out += '\n## Licence texts\n';
for (const n of names) {
  const text = licenseText(pkgDir(n));
  out += `\n### ${n} ${seen.get(n).version}\n\n${text ? '```text\n' + text + '\n```' : '_No licence file in the package; see the licence field above and the source repository._'}\n`;
}
for (const [title, file] of extra) {
  out += `\n### ${title}\n\n\`\`\`text\n${readFileSync(file, 'utf8').trim()}\n\`\`\`\n`;
}
writeFileSync('THIRD-PARTY-NOTICES.md', out);
console.log(`wrote THIRD-PARTY-NOTICES.md: ${names.length} packages, ${extra.length} data licences, ${(out.length / 1024).toFixed(0)} KB`);
